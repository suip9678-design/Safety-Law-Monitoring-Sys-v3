-- =====================================================================
--  개발용 H2 스키마 (Oracle 호환 모드)
-- =====================================================================
--  Oracle 서버 없이 애플리케이션을 띄워보기 위한 것이다.
--  운영 스키마는 db/schema-oracle.sql 이며, 그쪽이 기준이다.
--
--  두 파일의 차이는 H2 가 지원하지 않는 표기뿐이다.
--    - VARCHAR2(n CHAR) -> VARCHAR(n)   (H2 는 CHAR 단위 표기를 모른다)
--    - SYSTIMESTAMP     -> CURRENT_TIMESTAMP
--    - DBMS_LOB.INSTR   -> 아래에서 같은 이름의 함수를 직접 만들어 준다
--
--  H2 에서 동작한다고 해서 Oracle 10g 에서 동작한다는 뜻은 아니다.
--  최종 확인은 반드시 실제 Oracle 에서 해야 한다.
-- =====================================================================

-- 본문 검색에 쓰는 DBMS_LOB.INSTR 을 H2 에도 같은 이름으로 만들어 둔다.
-- 이렇게 해야 매퍼 SQL 을 H2 용으로 따로 관리하지 않아도 된다.
-- Oracle 의 INSTR 과 동일하게 1부터 세고, 못 찾으면 0 을 돌려준다.
CREATE SCHEMA IF NOT EXISTS DBMS_LOB;
CREATE ALIAS IF NOT EXISTS DBMS_LOB.INSTR AS '
int instr(String haystack, String needle) {
    if (haystack == null || needle == null) {
        return 0;
    }
    return haystack.indexOf(needle) + 1;
}
';

CREATE TABLE IF NOT EXISTS TRACKED_LAWS (
    ID                        NUMBER(19)    NOT NULL PRIMARY KEY,
    SOURCE_TYPE               VARCHAR(16)   NOT NULL,
    EXTERNAL_ID               VARCHAR(64)   NOT NULL,
    MASTER_ID                 VARCHAR(64),
    NAME                      VARCHAR(255)  NOT NULL,
    CATEGORY                  VARCHAR(64),
    DEPARTMENT                VARCHAR(128),
    CURRENT_PROMULGATION_NO   VARCHAR(64),
    CURRENT_PROMULGATION_DATE VARCHAR(16),
    CURRENT_ENFORCEMENT_DATE  VARCHAR(16),
    DETAIL_LINK               VARCHAR(512),
    IS_ACTIVE                 NUMBER(1)     DEFAULT 1 NOT NULL,
    LAST_SYNCED_AT            TIMESTAMP,
    CREATED_AT                TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT                TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_TRACKED_LAWS_SRC UNIQUE (SOURCE_TYPE, EXTERNAL_ID)
);
CREATE SEQUENCE IF NOT EXISTS SEQ_TRACKED_LAWS START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS LAW_REVISIONS (
    ID                         NUMBER(19)   NOT NULL PRIMARY KEY,
    TRACKED_LAW_ID             NUMBER(19)   NOT NULL,
    PROMULGATION_NO            VARCHAR(64),
    PROMULGATION_DATE          VARCHAR(16),
    ENFORCEMENT_DATE           VARCHAR(16),
    PREVIOUS_PROMULGATION_NO   VARCHAR(64),
    PREVIOUS_PROMULGATION_DATE VARCHAR(16),
    PREVIOUS_ENFORCEMENT_DATE  VARCHAR(16),
    DETECTED_AT                TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    REVIEW_STATUS              VARCHAR(16)  DEFAULT '미검토' NOT NULL,
    REVIEWER                   VARCHAR(64),
    REVIEWED_AT                TIMESTAMP,
    NOTE                       CLOB,
    RAW_DATA                   CLOB,
    CONSTRAINT FK_LAW_REV_TRACKED FOREIGN KEY (TRACKED_LAW_ID)
        REFERENCES TRACKED_LAWS (ID) ON DELETE CASCADE
);
CREATE SEQUENCE IF NOT EXISTS SEQ_LAW_REVISIONS START WITH 1 INCREMENT BY 1;

